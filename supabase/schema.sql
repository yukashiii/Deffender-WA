create table if not exists public.vip_tokens (
  id bigint generated by default as identity primary key,
  token text not null unique,
  is_active boolean not null default true,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.vip_tokens enable row level security;
-- No client policies: only the Edge Function service role validates tokens.
-- Never put SUPABASE_SERVICE_ROLE_KEY in the Android app.
